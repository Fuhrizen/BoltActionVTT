/** Rebuild plain SVG infantry assets; runtime paths never use data URIs. */
import {mkdir,writeFile} from 'node:fs/promises';
import {renderInfantry,infantryWeaponSlugs} from '../scripts/token-art/infantry.mjs';
import {infantryAssetKey,personalWeapons} from '../scripts/token-art/asset-keys.mjs';
import {palettes} from '../scripts/services/faction-appearance.mjs';
const manifest={};let count=0;
for(const [faction,palette] of Object.entries(palettes)){
 const dir=new URL(`../assets/tokens/infantry/${faction}/`,import.meta.url);await mkdir(dir,{recursive:true});
 for(const weaponSlug of infantryWeaponSlugs){
  const roles=['','crew',...(personalWeapons.includes(weaponSlug)?['nco','loader','medic','observer']:[])];
  for(const role of roles)for(const extras of [[],...(faction==='germany'&&personalWeapons.includes(weaponSlug)?[['panzerfaust']]:[])]){
   const options={weaponSlug,roles:role?[role]:[],extras},key=infantryAssetKey(options),path=`assets/tokens/infantry/${faction}/${key}.svg`;
   await writeFile(new URL(key+'.svg',dir),renderInfantry({palette,...options}));manifest[faction+':'+key]=path;count++;
  }
 }
}
await writeFile(new URL('../scripts/token-art/infantry-manifest.mjs',import.meta.url),'// Generated by tools/token-infantry.mjs.\nexport const infantryTokenAssets=Object.freeze('+JSON.stringify(manifest,null,2)+');\n');
console.log(`Generated ${count} file-backed infantry variants.`);
