/** Rebuild checked-in vehicle silhouettes: node tools/token-vehicles.mjs. */
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {renderVehicle} from '../scripts/token-art/vehicles.mjs';
const root=new URL('../',import.meta.url);
import {palettes} from '../scripts/services/faction-appearance.mjs';
export async function generateVehicles(){
 const rows=JSON.parse(await readFile(new URL('compendiums/units.json',root),'utf8')).filter(row=>row.system?.kind==='vehicle');
 const manifest={};
 for(const row of rows){
  const directory=`assets/tokens/vehicles/${row.factionSlug||'generic'}`;
  await mkdir(new URL(directory+'/',root),{recursive:true});
  const path=`${directory}/${row.slug}.svg`;
  await writeFile(new URL(path,root),renderVehicle({row,palette:palettes[row.factionSlug]}));
  manifest[row.slug]=path;
 }
 await writeFile(new URL('scripts/token-art/vehicle-manifest.mjs',root),`// Generated by tools/token-vehicles.mjs.\nexport const vehicleTokenAssets=Object.freeze(${JSON.stringify(manifest,null,2)});\n`);
 return rows.length;
}
if(process.argv[1]===fileURLToPath(import.meta.url))console.log(`Generated ${await generateVehicles()} vehicle silhouettes.`);
