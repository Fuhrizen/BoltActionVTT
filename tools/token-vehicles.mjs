/** Rebuild tracked SVG vehicle profiles and their source upgrade layers. */
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {renderVehicle} from '../scripts/token-art/vehicles.mjs';
import {vehicleVisualKey,vehicleVisualLabels} from '../scripts/token-art/asset-keys.mjs';
import {palettes} from '../scripts/services/faction-appearance.mjs';
const root=new URL('../',import.meta.url);
export async function generateVehicles(){
 const rows=JSON.parse(await readFile(new URL('compendiums/units.json',root),'utf8')).filter(row=>row.system?.kind==='vehicle');
 const manifest={},variants={};let count=0;
 for(const row of rows){
  const directory=`assets/tokens/vehicles/${row.factionSlug||'generic'}`;await mkdir(new URL(directory+'/',root),{recursive:true});
  const optionKeys=(row.profile?.options??[]).map(o=>vehicleVisualKey([o]));
  const keys=new Set([0,128]);for(const option of optionKeys)for(const key of [...keys])keys.add(key|option);
  for(const key of keys){
   const path=`${directory}/${row.slug}${key?'--v'+key:''}.svg`;
   await writeFile(new URL(path,root),renderVehicle({row,palette:palettes[row.factionSlug],options:vehicleVisualLabels(key)}));variants[row.slug+':'+key]=path;count++;
   if(!key)manifest[row.slug]=path;
  }
 }
 await writeFile(new URL('scripts/token-art/vehicle-manifest.mjs',root),`// Generated by tools/token-vehicles.mjs.\nexport const vehicleTokenAssets=Object.freeze(${JSON.stringify(manifest,null,2)});\nexport const vehicleTokenVariants=Object.freeze(${JSON.stringify(variants,null,2)});\n`);
 return count;
}
if(process.argv[1]===fileURLToPath(import.meta.url))console.log(`Generated ${await generateVehicles()} vehicle silhouettes and variants.`);
